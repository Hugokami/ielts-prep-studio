  function filterAndRenderAll() {
    const atGrid = document.getElementById("at-culinary-grid");
    const vtGrid = document.getElementById("vt-culinary-grid");
    const countEl = document.getElementById("at-culinary-count");

    const filtered = (window.BURMESE_CUISINE_DATA || []).filter((item) => {
      const matchesCat =
        activeCategory === "all" ||
        item.category.toLowerCase() === activeCategory.toLowerCase();

      if (!matchesCat) return false;

      if (!activeSearchQuery) return true;

      const q = activeSearchQuery;
      const matchNameEn = item.nameEn.toLowerCase().includes(q);
      const matchNameMm = item.nameMm.includes(q);
      const matchTagline = (item.tagline || "").toLowerCase().includes(q);
      const matchDesc = (item.ieltsBandDescription || "").toLowerCase().includes(q);
      const matchIngEn = (item.ingredientsEn || []).some((ing) => ing.toLowerCase().includes(q));
      const matchIngMm = (item.ingredientsMm || []).some((ing) => ing.includes(q));

      return matchNameEn || matchNameMm || matchTagline || matchDesc || matchIngEn || matchIngMm;
    });

    if (countEl) {
      countEl.textContent = `${filtered.length} of ${window.BURMESE_CUISINE_DATA.length} items`;
    }

    if (atGrid) atGrid.innerHTML = renderCardsHtml(filtered);
    if (vtGrid) vtGrid.innerHTML = renderCardsHtml(filtered);
  }

